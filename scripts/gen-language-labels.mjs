/**
 * Generates `src/editor/languageLabels.generated.ts` — the extension → language-name table
 * the status bar reads.
 *
 * ## Why this is generated rather than looked up at runtime
 *
 * The obvious implementation is `LanguageDescription.matchFilename(languages, name).name`.
 * It is not available here: `state/documents.ts` imports the label module on the boot path,
 * and importing `@codemirror/language-data` there once pulled ~550 kB of editor into the
 * initial chunk of an app whose first screen has no editor on it (see the header comment in
 * `src/editor/languageLabels.ts`). Emitting the table at build time keeps full coverage of
 * all ~220 extensions at a cost of a few kB of short strings and zero runtime dependency.
 *
 * ## Why this is generated rather than hand-maintained
 *
 * The hand table it replaces named 56 of 223 highlightable extensions, so files highlighted
 * correctly and then reported themselves as "Plain Text". Any hand list drifts the moment
 * `@codemirror/language-data` adds a grammar. `languageLabels.test.ts` re-derives this table
 * from the dependency and fails if the two disagree, so drift breaks the build instead of
 * shipping.
 *
 * Run after upgrading `@codemirror/language-data`:
 *
 *     node scripts/gen-language-labels.mjs
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { languages } from "@codemirror/language-data";

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "editor",
  "languageLabels.generated.ts",
);

/**
 * Builds extension → language name.
 *
 * First writer wins, matching `LanguageDescription.matchFilename`, which returns the first
 * description whose extension list contains the candidate. Generating in the same order the
 * runtime resolver walks keeps the label and the grammar that actually loads in agreement —
 * `.ts`, for instance, is claimed by both TypeScript and Typst-adjacent modes in some
 * versions, and the label has to name whichever one CodeMirror picks.
 */
export function buildLabelMap(descriptions) {
  const map = {};
  for (const desc of descriptions) {
    for (const ext of desc.extensions ?? []) {
      const key = ext.toLowerCase();
      if (!(key in map)) map[key] = desc.name;
    }
  }
  return map;
}

const map = buildLabelMap(languages);
const entries = Object.entries(map).sort(([a], [b]) => a.localeCompare(b));

const body = entries
  .map(([ext, name]) => `  ${JSON.stringify(ext)}: ${JSON.stringify(name)},`)
  .join("\n");

const source = `// @generated by scripts/gen-language-labels.mjs — do not edit by hand.
// Regenerate after upgrading @codemirror/language-data:  node scripts/gen-language-labels.mjs
// Drift from the dependency is caught by src/editor/languageLabels.test.ts.

/**
 * Extension (without the dot, lowercased) → language name, derived from every
 * \`LanguageDescription\` in \`@codemirror/language-data\` that declares an extension map.
 *
 * ${entries.length} extensions across ${new Set(Object.values(map)).size} languages. Held as
 * plain data so the boot path can read a label without importing CodeMirror (see the
 * generator's header for why that matters).
 */
export const GENERATED_LABELS: Record<string, string> = {
${body}
};
`;

writeFileSync(OUT, source, "utf8");
console.log(`wrote ${entries.length} extensions → ${OUT}`);
